const dictionaries: Record<Locale, Messages> = { en, 'zh-CN': zhCN, 'zh-TW': zhTW };

export function messages(locale: Locale): Messages {
  return dictionaries[locale] ?? en;
}

export function detectLocale(): Locale {
  const saved = localStorage.getItem('localsendy-locale') as Locale | null;
  if (saved && saved in dictionaries) return saved;
  return navigator.language.toLowerCase().startsWith('zh')
    ? navigator.language.toLowerCase().includes('tw') || navigator.language.toLowerCase().includes('hk')
      ? 'zh-TW'
      : 'zh-CN'
    : 'en';
}
